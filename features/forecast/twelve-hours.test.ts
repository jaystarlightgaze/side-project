import { describe, expect, test } from "vitest";

import { askTimingHour } from "./twelve-hours";

describe("askTimingHour: 부탁 타이밍 문구의 첫 시각 → 십이시 (saju-chart-card AC5)", () => {
  test.each([
    ["주간보고가 끝난 14:40, 커피 들고 온 직후", "未時", "미시", "14:40"],
    ["오후 2시 40분, 팀장님이 자리로 돌아온 직후", "未時", "미시", "14:40"],
    ["오후 2시, 커피 한 잔 후가 좋습니다.", "未時", "미시", "14:00"],
    ["2시 반쯤 점심 소화가 끝났을 때", "未時", "미시", "14:30"],
    ["오전 10시 회의 전에 짧게", "巳時", "사시", "10:00"],
    ["점심 직후 12시 50분", "午時", "오시", "12:50"],
    ["오후 4시 이후, 퇴근 전 여유가 생길 때", "申時", "신시", "16:00"],
    ["오전 9시 정각", "巳時", "사시", "09:00"],
    ["밤 11시 반은 피하세요", "子時", "자시", "23:30"],
    ["0:30", "子時", "자시", "00:30"],
    ["1:00", "丑時", "축시", "01:00"],
    ["오전 3시", "寅時", "인시", "03:00"],
    ["오전 5시", "卯時", "묘시", "05:00"],
    ["오전 7시 출근 직후", "辰時", "진시", "07:00"],
    ["오후 5시", "酉時", "유시", "17:00"],
    ["저녁 7시", "戌時", "술시", "19:00"],
    ["오후 9시", "亥時", "해시", "21:00"],
    ["13:00", "未時", "미시", "13:00"],
    ["12:59", "午時", "오시", "12:59"],
    ["오전 11시와 오후 3시 중 먼저", "午時", "오시", "11:00"],
  ])("%s → %s %s", (text, hanja, reading, time) => {
    expect(askTimingHour(text)).toEqual({ hanja, reading, time });
  });

  test("시간 길이(2시간)는 시각이 아니다", () => {
    expect(askTimingHour("회의가 2시간 이어지니 끝난 뒤에")).toBeNull();
  });

  test.each(["점심 먹고 기분이 좋아졌을 때", "", "주간보고가 끝난 직후"])("시각이 없으면 null: %s", (text) => {
    expect(askTimingHour(text)).toBeNull();
  });
});
